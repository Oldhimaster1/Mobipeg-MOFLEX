import {test,expect} from '@playwright/test';
test('advanced overrides reach the worker, remain optional, and reset on mobile',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 // Exercise the form and job lifecycle without running a real conversion here.
 await page.addInitScript(()=>{window.commands=[];window.Worker=class{constructor(){}postMessage(d){window.commands.push(d);}terminate(){}};});
 await page.goto('/');
 await expect(page.locator('#adv-subme')).toBeDisabled();
 await page.locator('.advanced > summary').click();
 await expect(page.locator('#advancedControls')).toBeHidden();
 await page.locator('#advancedEnabled').check();
 await page.locator('#adv-subme').fill('2');
 await page.locator('#adv-me').selectOption('dia');
 await page.locator('#adv-volume').fill('-6');
 await expect(page.locator('#advancedCommand')).toContainText('MOBI_SUBME=2');
 await expect(page.locator('#advancedCommand')).toContainText("'-me_method' 'dia'");
 await expect(page.locator('#advancedCommand')).toContainText('volume=-6dB,apad');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await page.locator('#file').setInputFiles({name:'form-fixture.mp4',mimeType:'video/mp4',buffer:Buffer.from('form fixture, no media encoding')});
 await page.locator('#convert').click();
 await expect.poll(()=>page.evaluate(()=>window.commands.length)).toBe(1);
 expect(await page.evaluate(()=>window.commands[0].settings.advanced)).toEqual({subme:2,me:'dia',volume:-6});
 await expect(page.locator('#advancedEnabled')).toBeDisabled();
 await page.locator('#cancel').click();
 await expect(page.locator('#adv-subme')).toBeEnabled();
 await page.locator('#adv-subme').fill('1');
 await expect(page.locator('#advancedCommand')).toContainText('Invalid subme');
 await page.locator('#advancedEnabled').uncheck();
 await expect(page.locator('#adv-subme')).toBeDisabled();
 await page.locator('#convert').click();
 await expect.poll(()=>page.evaluate(()=>window.commands.length)).toBe(2);
 expect(await page.evaluate(()=>window.commands[1].settings.advanced)).toBeNull();
 await page.locator('#cancel').click();
 await page.locator('#advancedEnabled').check();
 await page.locator('#reset').click();
 await expect(page.locator('#advancedEnabled')).not.toBeChecked();
 await expect(page.locator('#advancedControls')).toBeHidden();
 await expect(page.locator('#adv-subme')).toHaveValue('');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 expect(errors).toEqual([]);
});
